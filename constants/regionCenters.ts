export function getRegionCenter(region: string): RegionCenter | null {
  if (!region) return null;
  const direct = REGION_CENTERS[region];
  if (direct) return direct;
  const normalized = region.trim();
  for (const [key, coords] of Object.entries(REGION_CENTERS)) {
    if (key.toLowerCase() === normalized.toLowerCase()) return coords;
  }
  return null;
}
